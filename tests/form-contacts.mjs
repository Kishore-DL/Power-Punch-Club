import assert from 'node:assert/strict';
import {formContacts,formContactConfigurationError,documentContactVisible} from '../lib/form-contacts.mjs';
const fields=[{id:'n',label:'Participant',type:'text',contactRole:'name',required:true},{id:'p',label:'Mobile',type:'tel',contactRole:'phone',required:true},{id:'e',label:'Email',type:'email',contactRole:'email'}];
assert.deepEqual(formContacts(fields,{n:' Arun ',p:'+91 99999 99999',e:' ARUN@example.invalid '}),{name:'Arun',phone:'9999999999',email:'arun@example.invalid'});
assert.deepEqual(formContacts([{id:'city',label:'City',type:'text'}],{city:'Vellore'}),{name:'',phone:'',email:''});
assert.deepEqual(formContacts(fields.map(field=>({...field,required:false})),{}),{name:'',phone:'',email:''});
assert.throws(()=>formContacts(fields,{p:'9999999999'}),/Complete Participant/);
assert.throws(()=>formContacts(fields,{n:'Arun',p:'999'}),/10 digits/);
assert.throws(()=>formContacts(fields,{n:'Arun',p:'9999999999',e:'bad'}),/valid email/);
assert.throws(()=>formContacts(fields,{n:'A'.repeat(121),p:'9999999999'}),/120 characters/);
assert.throws(()=>formContacts(fields,{n:{name:'Arun'},p:'9999999999'}),/valid answer/);
assert.ok(formContactConfigurationError([...fields,{...fields[0],id:'other'}]));
assert.ok(formContactConfigurationError([{...fields[0],type:'file'}]));
assert.ok(formContactConfigurationError([{...fields[0],contactRole:'token'}]));
assert.ok(formContactConfigurationError([fields[0],fields[0]]));
const legacy={name:'Legacy Person',phone:'9999999999',email:'legacy@example.invalid'};
assert.deepEqual(formContacts([],{},{...legacy}),legacy);
assert.throws(()=>formContacts([],{}, {...legacy,email:'invalid'}),/valid email/);
assert.throws(()=>formContacts([],{}, {name:'Legacy Person'}),/email/);
assert.equal(formContacts([],{}, {...legacy,email:undefined},{emailOptional:true}).email,'');
assert.equal(formContacts(fields,{n:'Correct student',p:'8888888888'},legacy).name,'Correct student');
// Labels/reordering do not change contact identity; no guessed "name" fields.
assert.equal(formContacts([...fields].reverse().map(field=>({...field,label:'Renamed'})),{n:'Arun',p:'9999999999'}).name,'Arun');
assert.equal(formContacts([{id:'master',label:'Name',type:'text'}],{master:'Kumar'}).name,'');
assert.equal(documentContactVisible({},'name'),true);
assert.equal(documentContactVisible({receiptFields:{n:{contactRole:'name',showOnReceipt:false}}},'name'),false);
assert.equal(documentContactVisible({receiptFields:{n:{contactRole:'name',showOnReceipt:true}}},'name'),true);
assert.equal(documentContactVisible({receiptFields:{n:{contactRole:'name',label:'Private token'}}},'name'),false);
console.log('Manual contact mapping passed: configured roles, no automatic contacts, optional/required, renamed/reordered fields, +91/email normalization, validation, spoofed legacy precedence and legacy client compatibility.');
